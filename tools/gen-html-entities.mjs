// tools/gen-html-entities.mjs
//
// Generates src/odt/to-markdown/html-entities.ts, the named character
// reference table the Markdown emitter's attribute decoder uses, from the
// WHATWG HTML Standard's entities.json.
//
// Usage (from the odf-kit2 root):
//   node tools/gen-html-entities.mjs <path-to-entities.json>
//
// The directory holding entities.json must also hold the fetched
// html-spec.html (the licence sentence is read from it) and a PROVENANCE.md
// recording entities.json's fetch time, as odf-kit-internal spec/whatwg/ does.
//
// The generated header is a legal comment (/*! … */) so it survives the build
// (T4: Q2, Scott, 2026-10-20). It quotes the HTML Standard's licence sentence
// verbatim, then the BSD 3-Clause licence text as published at the URL that
// sentence links (T4: [L37], Scott, 2026-10-20). The last step runs the repo's
// own Prettier on the output, so the committed file is exactly this
// generator's output and is never hand-edited.

import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { execSync } from "node:child_process";

const OUT = "src/odt/to-markdown/html-entities.ts";
const SOURCE_URL = "https://html.spec.whatwg.org/entities.json";
const CC_BY_URL = "https://creativecommons.org/licenses/by/4.0/";
const BSD_URL = "https://opensource.org/licenses/BSD-3-Clause";
// BSD 3-Clause licence text as published at BSD_URL (fetched 2026-10-20; the
// copyright line is the published template, quoted as published per [L37]).
const BSD_TEXT = [
  "Copyright <YEAR> <COPYRIGHT HOLDER>",
  "Redistribution and use in source and binary forms, with or without modification, are permitted provided that the following conditions are met:",
  "1. Redistributions of source code must retain the above copyright notice, this list of conditions and the following disclaimer.",
  "2. Redistributions in binary form must reproduce the above copyright notice, this list of conditions and the following disclaimer in the documentation and/or other materials provided with the distribution.",
  "3. Neither the name of the copyright holder nor the names of its contributors may be used to endorse or promote products derived from this software without specific prior written permission.",
  "THIS SOFTWARE IS PROVIDED BY THE COPYRIGHT HOLDERS AND CONTRIBUTORS “AS IS” AND ANY EXPRESS OR IMPLIED WARRANTIES, INCLUDING, BUT NOT LIMITED TO, THE IMPLIED WARRANTIES OF MERCHANTABILITY AND FITNESS FOR A PARTICULAR PURPOSE ARE DISCLAIMED. IN NO EVENT SHALL THE COPYRIGHT HOLDER OR CONTRIBUTORS BE LIABLE FOR ANY DIRECT, INDIRECT, INCIDENTAL, SPECIAL, EXEMPLARY, OR CONSEQUENTIAL DAMAGES (INCLUDING, BUT NOT LIMITED TO, PROCUREMENT OF SUBSTITUTE GOODS OR SERVICES; LOSS OF USE, DATA, OR PROFITS; OR BUSINESS INTERRUPTION) HOWEVER CAUSED AND ON ANY THEORY OF LIABILITY, WHETHER IN CONTRACT, STRICT LIABILITY, OR TORT (INCLUDING NEGLIGENCE OR OTHERWISE) ARISING IN ANY WAY OUT OF THE USE OF THIS SOFTWARE, EVEN IF ADVISED OF THE POSSIBILITY OF SUCH DAMAGE.",
];

const input = process.argv[2];
if (!input) {
  console.error("usage: node tools/gen-html-entities.mjs <path-to-entities.json>");
  process.exit(2);
}
const dir = dirname(input);
const bytes = readFileSync(input);
const sha256 = createHash("sha256").update(bytes).digest("hex");
const entities = JSON.parse(bytes.toString("utf8"));

// Fetch time: the `fetched:` field of the entities.json entry in PROVENANCE.md.
const prov = readFileSync(join(dir, "PROVENANCE.md"), "utf8");
const fetched = prov.match(/^- entities\.json\n {2}- URL: .*\n {2}- fetched: (\S+)$/m)?.[1];
if (!fetched) throw new Error("PROVENANCE.md: no fetch time for entities.json");

// Licence sentence: the three lines of html-spec.html starting at the line that
// links the CC BY 4.0 licence and ending "instead.</p>".
const html = readFileSync(join(dir, "html-spec.html"), "utf8").split("\n");
const at = html.findIndex((l) => l.includes(`rel="license" href="${CC_BY_URL}"`));
if (at < 0 || !html[at].includes("Copyright © WHATWG")) throw new Error("licence sentence not found");
const sentence = html.slice(at, at + 3).map((l) => l.trim());
if (!sentence[2].endsWith("instead.</p>") || !sentence[2].includes(`href="${BSD_URL}"`)) {
  throw new Error("licence sentence does not end as expected");
}
for (const l of [...sentence, ...BSD_TEXT]) if (l.includes("*/")) throw new Error("comment terminator in quoted text");

const names = Object.keys(entities);
const rows = names.map((name) => `  [${JSON.stringify(name)}, ${JSON.stringify(entities[name].characters)}],`);

const out = `/*!
 * HTML named character references, from the WHATWG HTML Standard's entities.json.
 *
 * Source: ${SOURCE_URL}
 * Fetched: ${fetched}
 * sha256: ${sha256}
 * Generated by tools/gen-html-entities.mjs; never hand-edit.
 *
 * The HTML Standard's licence sentence (html-spec.html l.${at + 1}–${at + 3}), verbatim:
 *
${sentence.map((l) => ` *   ${l}`).join("\n")}
 *
 * The BSD 3-Clause License, as published at ${BSD_URL}:
 *
${BSD_TEXT.map((p) => ` *   ${p}`).join("\n *\n")}
 */

/**
 * Name → characters, keyed exactly as entities.json spells each name (the
 * leading "&" kept; with or without the trailing ";", as listed). ${names.length} entries.
 */
export const HTML_ENTITIES: ReadonlyMap<string, string> = Object.freeze(
  new Map<string, string>([
${rows.join("\n")}
  ]),
);
`;
writeFileSync(OUT, out);
execSync(`npx prettier --write ${OUT}`, { stdio: "inherit" });
console.log(`${OUT}: ${names.length} entries; sha256 of input ${sha256}`);
